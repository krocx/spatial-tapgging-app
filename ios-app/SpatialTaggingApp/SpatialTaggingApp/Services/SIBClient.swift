    private func post<B: Encodable, R: Decodable>(
        _ type: R.Type, path: String, body: B, timeout: TimeInterval? = nil
    ) async throws -> R {
        var req = try makeRequest(method: "POST", path: path)
        if let timeout { req.timeoutInterval = timeout } // #73: per-operation override
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        req.httpBody = try JSONEncoder().encode(body)
        return try await perform(req, decoding: type)
    }

    private func patch<B: Encodable, R: Decodable>(_ type: R.Type, path: String, body: B) async throws -> R {
        var req = try makeRequest(method: "PATCH", path: path)
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        req.httpBody = try JSONEncoder().encode(body)
        return try await perform(req, decoding: type)
    }

    private func perform<T: Decodable>(_ request: URLRequest, decoding type: T.Type) async throws -> T {
        let (data, response): (Data, URLResponse)
        do { (data, response) = try await session.data(for: request) }
        catch { throw SIBClientError.networkError(error) }

        if let http = response as? HTTPURLResponse, !(200...299).contains(http.statusCode) {
            let msg = (try? JSONDecoder().decode(APIError.self, from: data))?.error
                ?? String(data: data, encoding: .utf8) ?? "Unknown error"
            throw SIBClientError.httpError(http.statusCode, msg)
        }

        let decoder = JSONDecoder()
        if let envelope = try? decoder.decode(APIResponse<T>.self, from: data) { return envelope.data }
        do { return try decoder.decode(T.self, from: data) }
        catch { throw SIBClientError.decodingError(error) }
    }

    private func makeRequest(method: String, path: String) throws -> URLRequest {
        guard settings.isConfigured else { throw SIBClientError.notConfigured }
        let raw = settings.normalizedBaseURL + path
        guard let url = URL(string: raw) else { throw SIBClientError.invalidURL(raw) }
        var req = URLRequest(url: url)
        req.httpMethod = method
        // Phase 2.5 — API key auth: send X-API-Key on every request.
        // The SIB ignores this header when SIB_API_KEY env var is not set (local dev).
        let key = settings.apiKey.trimmingCharacters(in: .whitespaces)
        if !key.isEmpty {
            req.setValue(key, forHTTPHeaderField: "X-API-Key")
        }
        // UAM identity (RBAC): carried on EVERY request so the server can
        // enforce roles and per-user guide sharing. Empty until verified.
        if !settings.uamToken.isEmpty {
            req.setValue(settings.uamToken, forHTTPHeaderField: "X-User-Token")
        }
        return req
    }


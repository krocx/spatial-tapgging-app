    /// Fetch the canonical QR PNG generated by the server at anchor creation.
    /// Both the iOS app (QRGeneratorView) and the portal display this image so
    /// all clients show the identical pixel pattern regardless of QR library.
    func fetchAnchorQRImage(anchorId: String) async throws -> Data {
        let req = try makeRequest(method: "GET", path: "/anchors/\(anchorId)/qrimage")
        let (data, response): (Data, URLResponse)
        do { (data, response) = try await session.data(for: req) }
        catch { throw SIBClientError.networkError(error) }
        if let http = response as? HTTPURLResponse, !(200...299).contains(http.statusCode) {
            let msg = (try? JSONDecoder().decode(APIError.self, from: data))?.error ?? "HTTP \(http.statusCode)"
            throw SIBClientError.httpError(http.statusCode, msg)
        }
        return data
    }

    /// Upload a serialised ARWorldMap (NSKeyedArchiver binary plist) for an anchor.
    /// The server stores it so subsequent sessions can relocalize into the same
    /// feature-point cloud, giving scan-position-independent tag placement.
    func uploadWorldMap(anchorId: String, data: Data) async throws {
        var req = try makeRequest(method: "POST", path: "/anchors/\(anchorId)/worldmap")
        req.timeoutInterval = 90 // #73: large binary payload, needs more than the 20s CRUD default
        req.setValue("application/octet-stream", forHTTPHeaderField: "Content-Type")
        req.httpBody = data
        let (_, response): (Data, URLResponse)
        do { (_, response) = try await session.data(for: req) }
        catch { throw SIBClientError.networkError(error) }
        if let http = response as? HTTPURLResponse, !(200...299).contains(http.statusCode) {
            throw SIBClientError.httpError(http.statusCode, "World map upload failed (\(http.statusCode))")
        }
    }

    /// Download a previously stored ARWorldMap binary for an anchor.
    /// Returns nil (does NOT throw) on 404 — meaning no map has been saved yet
    /// and the caller should start a fresh session instead.
    func fetchWorldMap(anchorId: String) async throws -> Data? {
        var req = try makeRequest(method: "GET", path: "/anchors/\(anchorId)/worldmap")
        req.timeoutInterval = 45 // #73: larger-than-CRUD binary download
        let (data, response): (Data, URLResponse)
        do { (data, response) = try await session.data(for: req) }
        catch { throw SIBClientError.networkError(error) }
        guard let http = response as? HTTPURLResponse else { return nil }
        if http.statusCode == 404 { return nil }            // no map stored yet — normal first-session case
        if !(200...299).contains(http.statusCode) {
            throw SIBClientError.httpError(http.statusCode, "World map download failed (\(http.statusCode))")
        }
        return data
    }

